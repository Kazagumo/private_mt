#!/usr/bin/env python3
"""
构造静态 Trie 的生成器。
输入: 每行: 文字 <tab or space> 拼音(可含空格) <tab or space> 权重
输出: C++ 头文件，包含静态数组表示的 Trie 树。

用法: python3 trie_static_generator.py pinyin_simp.dict.yaml pinyin_trie_static.h
"""
import sys
import os
import argparse

weights_exclude = -1 # minimum weight accepted for device

words_included = []

parser = argparse.ArgumentParser(description="Generate a static C++ trie header from a pinyin word list")
parser.add_argument('input', help='input dictionary file')
parser.add_argument('output', help='output header file')
parser.add_argument('--progmem', '-p', action='store_true', help='annotate large arrays with PROGMEM (for AVR/embedded)')
args = parser.parse_args()

INPUT = args.input
OUTPUT = args.output
USE_PROGMEM = args.progmem

# Node structure in memory
class Node:
    __slots__ = ("children", "word_entries", "id")
    def __init__(self):
        self.children = {}  # token -> Node
        self.word_entries = []  # list of (word, weight)
        self.id = 9

root = Node()

# parse lines
def parse_line(line):
    line = line.strip()
    if not line or line.startswith('#'):
        return None
    parts = line.split()
    if len(parts) < 3:
        return None
    word = parts[0]
    weight = parts[-1]
    pinyin = " ".join(parts[1:-1])
    return word, pinyin, int(weight)

count = 0
with open(INPUT, encoding='utf-8') as f:
    for ln in f:
        res = parse_line(ln)
        if not res:
            continue
        word, pinyin, weight = res
        if (word+pinyin) in words_included:
            continue
        else:
            words_included.append((word+pinyin))
        # skip entries with low weight to reduce final binary size / noise
        if len(word) == 1 and weight < weights_exclude:
            continue
        if len(word) > 4:
            continue
        tokens = pinyin.split()
        node = root
        for tok in tokens:
            if tok not in node.children:
                node.children[tok] = Node()
            node = node.children[tok]
        node.word_entries.append((word, weight))
        count += 1

# Assign IDs to nodes and flatten
nodes = []

def assign_ids(node):
    node.id = len(nodes)
    nodes.append(node)
    # sort children to make deterministic output
    for tok in sorted(node.children.keys()):
        assign_ids(node.children[tok])

assign_ids(root)

# Gather unique tokens and map to ints
token_set = set()
for n in nodes:
    token_set.update(n.children.keys())

tokens = sorted(token_set)
token_to_id = {t:i for i,t in enumerate(tokens)}

# compute initials for each token (first ASCII letter) and build unique initial -> token_id mapping
def token_initial(t):
    for ch in t:
        if ch.isalpha():
            return ch.lower()
    return t[0]
token_initials_per_token = [token_initial(t) for t in tokens]
# unique initials in sorted order
unique_initials = sorted(set(token_initials_per_token))
initial_to_tokenids = {u: [] for u in unique_initials}
for tid, init in enumerate(token_initials_per_token):
    initial_to_tokenids[init].append(tid)
# flatten initial->tokenids mapping
initial_flat = []
initial_ranges = []
for u in unique_initials:
    start = len(initial_flat)
    initial_flat.extend(initial_to_tokenids[u])
    initial_ranges.append((start, len(initial_to_tokenids[u])))

# Build arrays: for each node, list of (token_id, child_node_id)
node_edges = []
for n in nodes:
    edges = [(token_to_id[t], n.children[t].id) for t in sorted(n.children.keys())]
    node_edges.append(edges)

# Build words pool and indices
words = []  # flat list of utf8 C strings
word_offsets = []  # for each node, (start, count)
word_char_counts = []
for n in nodes:
    start = len(words)
    for w,wt in n.word_entries:
        words.append((w, wt))
        # compute character count (unicode codepoints)
        word_char_counts.append(len(w))
    count_words = len(n.word_entries)
    word_offsets.append((start, count_words))

# Compute per-node subtree max weights so we can emit them into the header
INT_MIN = -2**31
node_count = len(nodes)
node_max_weights = [INT_MIN] * node_count
# process nodes in reverse order so children are computed before parents
for nid in range(node_count - 1, -1, -1):
    best = INT_MIN
    # local words
    start, cnt = word_offsets[nid]
    for i in range(cnt):
        wi = start + i
        wt = words[wi][1]
        if wt > best:
            best = wt
    # children
    for tokid, childid in node_edges[nid]:
        cw = node_max_weights[childid]
        if cw > best:
            best = cw
    node_max_weights[nid] = best

# Write header
guard = os.path.basename(OUTPUT).upper().replace('.', '_')
with open(OUTPUT, 'w', encoding='utf-8') as out:
    out.write("// Auto-generated by trie_static_generator.py from " + os.path.basename(INPUT) + "\n")
    out.write("#ifndef " + guard + "\n#define " + guard + "\n\n")
    out.write("#include <cstdint>\n#include <cstddef>\n#include <cstring>\n\n")
    out.write("#define WORDS_MAX_WEIGHT_SIZE "+str(len(node_max_weights))+"\n\n")
    # emit PROGMEM macro block if requested (cross-platform safe)
    if USE_PROGMEM:
        out.write("// PROGMEM compatibility: on AVR use <avr/pgmspace.h>, otherwise define empty\n")
        out.write("#ifndef PROGMEM\n")
        out.write("#if defined(__AVR__)\n#include <avr/pgmspace.h>\n#else\n#define PROGMEM\n#endif\n#endif\n\n")
    # tokens
    out.write("// " + str(len(tokens)) + " unique pinyin tokens\n")
    out.write("static const char* PINYIN_TOKENS[] = {\n")
    for t in tokens:
        out.write(f'    "{t}",\n')
    out.write("};\n\n")
    # unique initials and mapping to token ids
    #out.write("// unique token initials (single lowercase letter)\n")
    prog = " PROGMEM" if USE_PROGMEM else ""
    #out.write("static const char PINYIN_INITIALS[]" + prog + " = {\n")
    #for init in unique_initials:
    #    out.write(f"    '{init}',\n")
    #out.write("};\n\n")
    #out.write("// mapping from initial index -> flat token id list (indices into PINYIN_TOKENS)\n")
    #out.write("static const uint16_t INITIAL_TOKEN_IDS[]" + prog + " = {\n")
    #for tid in initial_flat:
    #    out.write(f"    {tid},\n")
    #out.write("};\n\n")
    #out.write("static const uint32_t INITIAL_TOKEN_RANGE[][2]" + prog + " = {\n")
    #for start,cnt in initial_ranges:
    #    out.write(f"    {{ {start}, {cnt} }},\n")
    #out.write("};\n\n")
    # nodes: edges offsets
    out.write("// Node edges: for each node, a range into NODE_EDGES (start,count)\n")
    # flatten edges
    flat_edges = []
    edge_ranges = []
    for edges in node_edges:
        start = len(flat_edges)
        for tokid, childid in edges:
            flat_edges.append((tokid, childid))
        edge_ranges.append((start, len(edges)))
    #out.write(f"static const uint16_t NODE_EDGE_COUNT = {len(flat_edges)};\n")
    out.write("struct Edge { uint32_t token_id; uint32_t child_node; };\n")
    out.write("static const Edge NODE_EDGES[]" + prog + " = {\n")
    for tokid, childid in flat_edges:
        out.write(f"    {{ {tokid}, {childid} }},\n")
    out.write("};\n\n")
    out.write("static const uint32_t NODE_EDGE_RANGE[][2]" + prog + " = {\n")
    for start, cnt in edge_ranges:
        out.write(f"    {{ {start}, {cnt} }},\n")
    out.write("};\n\n")
    # words: produce a concatenated string pool + offsets + weights
    out.write(f"// Words pool: {len(words)} entries (string pool + offsets + weights)\n")
    # Build concatenated data
    pool_bytes = bytearray()
    offsets = []
    weights = []
    for w,wt in words:
        safe = w.replace('"', '\\"')
        offsets.append(len(pool_bytes))
        b = safe.encode('utf-8')
        pool_bytes.extend(b)
        pool_bytes.append(0)
        weights.append(wt)
    out.write("static const unsigned char WORDS_DATA[]" + prog + " = {")
    # write as comma-separated byte values for UTF-8 bytes
    out.write('\n')
    for b in pool_bytes:
        out.write(f"    {b},\n")
    out.write("};\n\n")
    out.write("static const uint32_t WORDS_OFFSETS[]" + prog + " = {\n")
    for o in offsets:
        out.write(f"    {o},\n")
    out.write("};\n\n")
    out.write("static const uint32_t WORDS_MAX_WEIGHT[]" + prog + " = {\n")
    for wt in node_max_weights:
        out.write(f"    {wt},\n")
    out.write("};\n\n")
    out.write("static const uint32_t WORDS_WEIGHT[]" + prog + " = {\n")
    for wt in weights:
        out.write(f"    {wt},\n")
    out.write("};\n\n")
    # word char counts (number of unicode characters in the word)
    out.write("// character counts for each WORDS entry (number of Chinese characters)\n")
    out.write("static const uint8_t WORD_CHAR_COUNT[]" + prog + " = {\n")
    for cnt in word_char_counts:
        out.write(f"    {cnt},\n")
    out.write("};\n\n")
    out.write("static const uint32_t NODE_WORD_RANGE[][2]" + prog + " = {\n")
    for start, cnt in word_offsets:
        out.write(f"    {{ {start}, {cnt} }},\n")
    out.write("};\n\n")
    # lookup function sample
    out.write("#endif // " + guard + "\n")

print(f"Wrote {OUTPUT}, nodes={len(nodes)}, tokens={len(tokens)}, words={len(words)}")

